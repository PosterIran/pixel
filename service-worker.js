```js
// ============================================================
// Service Worker - پوستر ایران
// حالت: کاملاً آنلاین و بدون Cache
// ============================================================


// ------------------------------------------------------------
// 1. نصب نسخه جدید
// ------------------------------------------------------------

self.addEventListener('install', (event) => {

    console.log('🚀 Service Worker جدید نصب شد.');

    // فعال شدن فوری
    self.skipWaiting();

});


// ------------------------------------------------------------
// 2. فعال شدن نسخه جدید
// ------------------------------------------------------------

self.addEventListener('activate', (event) => {

    event.waitUntil(

        caches.keys()
            .then((cacheNames) => {

                // پاک کردن تمام Cache های قبلی
                return Promise.all(

                    cacheNames.map((cacheName) => {

                        console.log(
                            '🧹 حذف Cache قدیمی:',
                            cacheName
                        );

                        return caches.delete(cacheName);

                    })

                );

            })

            .then(() => {

                // کنترل فوری صفحات باز
                return self.clients.claim();

            })

            .then(() => {

                console.log(
                    '✅ Service Worker فعال شد؛ Cache کاملاً پاک شد.'
                );

            })

    );

});


// ------------------------------------------------------------
// 3. هیچ fetch handler وجود ندارد
// ------------------------------------------------------------
//
// عمداً این قسمت را حذف کرده‌ایم.
//
// بنابراین:
// HTML
// CSS
// JavaScript
// تصاویر
// فونت‌ها
// Manifest
//
// مستقیماً طبق رفتار عادی مرورگر از اینترنت دریافت می‌شوند.
//
// ------------------------------------------------------------


// ------------------------------------------------------------
// 4. دریافت فرمان از index.html
// ------------------------------------------------------------

self.addEventListener('message', (event) => {

    if (
        event.data &&
        event.data.action === 'skipWaiting'
    ) {

        console.log(
            '🔄 فعال‌سازی فوری Service Worker جدید...'
        );

        self.skipWaiting();

    }

});
```
